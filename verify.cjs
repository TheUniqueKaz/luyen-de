assert.equal(run('data.wrong.includes(2)'),false,'Correct retry removes the wrong-answer marker');
run('config.mode="exam";start();view="quiz";choose(0);choose(2);');
assert.equal(run('data.session.answers[1]'),2,'Exam answers may be changed');
